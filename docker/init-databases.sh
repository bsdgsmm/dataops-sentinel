#!/bin/bash
set -euo pipefail

psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<SQL
CREATE ROLE ${AIRFLOW_DB_USER} LOGIN PASSWORD '${AIRFLOW_DB_PASSWORD}';
CREATE DATABASE airflow OWNER ${AIRFLOW_DB_USER};
CREATE ROLE ${SENTINEL_DB_USER} LOGIN PASSWORD '${SENTINEL_DB_PASSWORD}';
CREATE DATABASE ${SENTINEL_DB_NAME} OWNER ${SENTINEL_DB_USER};
SQL
